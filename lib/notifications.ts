export function formatDailyReport(report: any): { subject: string; html: string; text: string } {
    const r = report.report || report;
    const headline = r.headline || 'Daily Update';
    const subject = `Morning Briefing: ${headline}`;

    // HTML
    const htmlSections = [
        r.readiness && textSection('Readiness', r.readiness),
        r.habitNote && textSection('Habits', r.habitNote),
        r.trainingRec && textSection('Training', r.trainingRec),
        r.reading && textSection('Reading', r.reading),
        r.projectTasks?.length && bulletSection('Projects', r.projectTasks),
        r.focusItems?.length && bulletSection("Today's Focus", r.focusItems),
        r.insight && textSection('Insight', r.insight),
    ].filter(Boolean).join('');
    const html = wrapEmail(headline, htmlSections);

    // Plain text fallback
    const textSections = [
        r.readiness && `READINESS\n${r.readiness}`,
        r.habitNote && `HABITS\n${r.habitNote}`,
        r.trainingRec && `TRAINING\n${r.trainingRec}`,
        r.reading && `READING\n${r.reading}`,
        r.projectTasks?.length && `PROJECTS\n${r.projectTasks.map((i: string) => `- ${i}`).join('\n')}`,
        r.focusItems?.length && `TODAY'S FOCUS\n${r.focusItems.map((i: string) => `- ${i}`).join('\n')}`,
        r.insight && `INSIGHT\n${r.insight}`,
    ].filter(Boolean).join('\n\n');
    const text = textSections || 'Your daily briefing is ready in Athena.';

    return { subject, html, text };
}

