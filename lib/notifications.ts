export function formatCoachNotes(workoutType: string, notes: any): { subject: string; html: string; text: string } {
    const subject = `Workout Coach: ${workoutType}`;
    const notesList: string[] = Array.isArray(notes?.notes) ? notes.notes : Array.isArray(notes) ? notes : [];
    const warnings: string[] = Array.isArray(notes?.warnings) ? notes.warnings.filter(Boolean) : [];
    const weightNotes: Record<string, string> = notes?.weightNotes || notes?.weight_notes || {};
    const exerciseOrder: string[] = notes?.exerciseOrder || notes?.exercise_order || [];

    // HTML
    let htmlSections = '';

    if (notesList.length > 0) {
        // First note is recovery assessment
        htmlSections += textSection('Recovery', notesList[0]);
        if (notesList.length > 1) {
            htmlSections += bulletSection('Strategy', notesList.slice(1));
        }
    }

    if (Object.keys(weightNotes).length > 0) {
        const orderedExercises = exerciseOrder.length > 0
            ? exerciseOrder.filter(e => weightNotes[e])
            : Object.keys(weightNotes);
        const exerciseItems = orderedExercises.map(e => `${e}: ${weightNotes[e]}`);
        htmlSections += bulletSection('Exercises', exerciseItems);
    }

    if (warnings.length > 0) {
        htmlSections += sectionBlock('Warning', `<p style="font-size:14px;color:#f87171;line-height:1.6;margin:0;">${escapeHtml(warnings[0])}</p>`);
    }

    const html = wrapEmail(`${workoutType} -- Pre-Workout`, htmlSections || sectionParagraph('Your pre-workout coach notes are ready in Athena.'));

    // Plain text fallback
    const textParts = [
        notesList.length > 0 && `COACH NOTES\n${notesList.join('\n')}`,
        Object.keys(weightNotes).length > 0 && `EXERCISES\n${(exerciseOrder.length > 0 ? exerciseOrder.filter(e => weightNotes[e]) : Object.keys(weightNotes)).map(e => `- ${e}: ${weightNotes[e]}`).join('\n')}`,
        warnings.length > 0 && `WARNING: ${warnings[0]}`,
    ].filter(Boolean).join('\n\n');
    const text = textParts || 'Your pre-workout coach notes are ready in Athena.';

    return { subject, html, text };
}
