// ── Email template helpers ──────────────────────────────────────────────────

function escapeHtml(str: string): string {
    return str
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;');
}

function sectionHeading(title: string): string {
    return `<h2 style="font-size:10px;letter-spacing:0.25em;text-transform:uppercase;color:#d4a843;margin:0 0 8px 0;font-family:-apple-system,Helvetica,Arial,sans-serif;font-weight:600;">${escapeHtml(title)}</h2>`;
}

function sectionParagraph(text: string): string {
    return `<p style="font-size:14px;color:#b8b0a0;line-height:1.6;margin:0;">${escapeHtml(text)}</p>`;
}

function sectionBlock(title: string, content: string): string {
    return `<div style="margin-bottom:20px;">${sectionHeading(title)}${content}</div>`;
}

function textSection(title: string, text: string): string {
    return sectionBlock(title, sectionParagraph(text));
}

function bulletSection(title: string, items: string[]): string {
    const bullets = items.map(item =>
        `<table cellpadding="0" cellspacing="0" border="0" style="margin-bottom:6px;"><tr><td style="vertical-align:top;padding-right:8px;color:#d4a843;font-size:14px;font-family:Georgia,serif;">--</td><td style="font-size:14px;color:#b8b0a0;line-height:1.6;font-family:Georgia,serif;">${escapeHtml(item)}</td></tr></table>`
    ).join('');
    return sectionBlock(title, bullets);
}

function wrapEmail(headline: string, sections: string): string {
    return `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" style="margin:0;padding:0;font-family:Georgia,'Times New Roman',serif;">
<tr>
<td align="center" style="padding:0;">
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" style="max-width:100%;background-color:#141414;border:1px solid rgba(212,168,67,0.2);border-radius:12px;">
<tr>
<td style="padding:32px;">
<div style="text-align:center;margin-bottom:24px;">
<span style="font-size:14px;letter-spacing:0.2em;color:#d4a843;text-transform:uppercase;font-family:-apple-system,Helvetica,Arial,sans-serif;">Athena</span>
</div>
<h1 style="font-size:20px;color:#e8e0d0;font-weight:400;line-height:1.4;margin:0 0 24px 0;font-family:Georgia,serif;">${escapeHtml(headline)}</h1>
${sections}
<div style="border-top:1px solid rgba(212,168,67,0.1);padding-top:16px;margin-top:24px;text-align:center;">
<span style="font-size:11px;color:#666;font-family:-apple-system,Helvetica,Arial,sans-serif;">Generated by Athena</span>
</div>
</td>
</tr>
</table>
</td>
</tr>
</table>`;
}

// ── Send notification ───────────────────────────────────────────────────────

export async function sendReportNotification(subject: string, html: string, text: string) {
    const apiKey = await getAppConfig('RESEND_API_KEY');
    const email = await getAppConfig('NOTIFICATION_EMAIL');

    if (!apiKey || !email) return; // Notifications not configured, skip silently

    try {
        await fetch('https://api.resend.com/emails', {
            method: 'POST',
            headers: {
                'Authorization': `Bearer ${apiKey}`,
                'Content-Type': 'application/json',
            },
            body: JSON.stringify({
                from: 'Athena <onboarding@resend.dev>',
                to: email,
                subject,
                html,
                text,
            }),
        });
    } catch (err) {
        console.error('[Notifications] Failed to send email:', err);
    }
}

